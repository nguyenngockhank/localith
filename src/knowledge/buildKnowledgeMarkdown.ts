import type { CrawlKnowledgeResult } from "../types.js";
import { escapeCell } from "../crawler/crawl/crawler.js";

/**
 * Builds a comprehensive Markdown document detailing the knowledge and keywords
 * of each screen and pattern group.
 */
export function buildKnowledgeMarkdown(
  knowledge: CrawlKnowledgeResult,
  runDir?: string
): string {
  const lines: string[] = [
    "# Application Screen Knowledge & Keywords Report",
    "",
    `- **Target:** ${knowledge.startUrl}`,
    `- **Generated:** ${knowledge.generatedAt}`,
    `- **Model:** ${knowledge.ollamaModel}`,
    `- **Total Unique Screens:** ${knowledge.totalScreens}`,
    `- **Group Pattern Screens:** ${knowledge.totalPatternGroups}`,
    "",
    "## Global Domain Keywords",
    "",
    knowledge.globalKeywords.length > 0
      ? knowledge.globalKeywords.map((kw) => `\`${kw}\``).join(" • ")
      : "—",
    "",
    "## Screens Summary",
    "",
    "| # | Screen Name | Type | Pattern / URL | Group? | Top Keywords |",
    "|---:|---|---|---|:---:|---|"
  ];

  knowledge.screens.forEach((screen, index) => {
    const topKeywords = screen.keywords.slice(0, 4).join(", ");
    lines.push(
      `| ${index + 1} | **${escapeCell(screen.screenName)}** | ${escapeCell(screen.screenType)} | \`${escapeCell(screen.pattern)}\` | ${screen.isPatternGroup ? "✓" : "—"} | ${escapeCell(topKeywords)} |`
    );
  });

  lines.push("", "---", "", "## Screen Details", "");

  for (const screen of knowledge.screens) {
    lines.push(
      `### ${screen.screenName}`,
      "",
      `- **Pattern / URL:** \`${screen.pattern}\``,
      `- **Screen Type:** \`${screen.screenType}\``,
      `- **Pattern Group:** ${screen.isPatternGroup ? "Yes (parameterized template)" : "No (static page)"}`,
      `- **Purpose:** ${screen.purpose}`,
      `- **Summary:** ${screen.summary}`,
      ""
    );

    if (screen.keyWorkflows.length > 0) {
      lines.push("**Key Workflows:**");
      screen.keyWorkflows.forEach((w) => lines.push(`- ${w}`));
      lines.push("");
    }

    if (screen.dataEntities.length > 0) {
      lines.push("**Data Entities & Models:**");
      screen.dataEntities.forEach((e) => lines.push(`- ${e}`));
      lines.push("");
    }

    if (screen.uiComponents.length > 0) {
      lines.push("**Key UI Components & Sections:**");
      screen.uiComponents.forEach((c) => lines.push(`- ${c}`));
      lines.push("");
    }

    if (screen.keywords.length > 0) {
      lines.push("**Keywords:**");
      lines.push(screen.keywords.map((kw) => `\`${kw}\``).join(", "));
      lines.push("");
    }

    if (screen.sampleUrls.length > 0) {
      lines.push("<details><summary>Sample URLs (" + screen.sampleUrls.length + ")</summary>", "");
      screen.sampleUrls.forEach((u) => lines.push(`- ${u}`));
      lines.push("", "</details>", "");
    }

    lines.push("---", "");
  }

  lines.push(
    "## Files",
    "",
    "- `knowledge.json`: complete machine-readable knowledge and keywords schema",
    "- `knowledge.md`: this human-readable architectural screen guide",
    "- `screens/*.json`: per-screen detailed knowledge artifact files",
    "",
    "_Generated by Local Website Scanner Knowledge Engine._",
    ""
  );

  return lines.join("\n");
}

