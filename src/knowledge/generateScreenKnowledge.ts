import { readFile, writeFile } from "node:fs/promises";
import fs from "node:fs";
import path from "node:path";
import { Ollama } from "ollama";
import type {
  CrawlReport,
  CrawledPage,
  ScreenKnowledge,
  CrawlKnowledgeResult
} from "../types.js";
import { isDynamicPattern, extractUrlPattern } from "../crawler/crawl/urlPattern.js";
import { readJsonFile, writeJson } from "../utils.js";
import { buildKnowledgeMarkdown } from "./buildKnowledgeMarkdown.js";
import { createFallbackScreenAnalysis } from "./createFallbackScreenAnalysis.js";
import { persistScreenKnowledgeState } from "./persistScreenKnowledgeState.js";
import { getOllamaClient } from "../ollama/getOllamaClient.js";

export interface GenerateKnowledgeOptions {
  ollamaUrl?: string;
  ollamaModel?: string;
  ollamaClient?: Ollama;
  runDir?: string;
  report?: CrawlReport;
  reportPath?: string;
  forceReanalyze?: boolean;
}

export interface ScreenGroup {
  pattern: string;
  isPatternGroup: boolean;
  pages: CrawledPage[];
}


/**
 * Groups pages into distinct screens: either dynamic pattern groups (e.g. /report-issues/{{id}})
 * or distinct static screen URLs.
 */
export function groupPagesForKnowledge(pages: readonly CrawledPage[]): ScreenGroup[] {
  const groups = new Map<string, ScreenGroup>();

  for (const page of pages) {
    const url = page.finalUrl || page.url;
    const pattern = page.pattern || extractUrlPattern(url);
    const isGroup = isDynamicPattern(pattern);
    const key = isGroup ? pattern : url;

    if (!groups.has(key)) {
      groups.set(key, {
        pattern: key,
        isPatternGroup: isGroup,
        pages: []
      });
    }

    groups.get(key)!.pages.push(page);
  }

  return Array.from(groups.values());
}

/**
 * Prompts Ollama to extract structured knowledge and keywords for a screen or screen group
 * using the accessibility tree snapshot generated by agent-browser.
 */
async function analyzeScreenWithOllama(
  client: Ollama,
  model: string,
  group: ScreenGroup,
  runDir?: string
): Promise<Omit<ScreenKnowledge, "screenId" | "pattern" | "isPatternGroup" | "sampleUrls">> {
  const okPages = group.pages.filter((p) => p.status === "ok");
  const samplePages = okPages.length > 0 ? okPages.slice(0, 3) : group.pages.slice(0, 3);

  // Aggregate representative titles and headings from the sampled screens
  const titles = Array.from(new Set(samplePages.map((p) => p.title).filter(Boolean))).join(" | ");
  const headings = samplePages
    .flatMap((p) => p.headings ?? [])
    .map((h) => `${h.tag.toUpperCase()}: ${h.text}`)
    .slice(0, 15)
    .join("\n");

  // Read the agent-browser snapshots for each sample page
  const snapshotSnippets: string[] = [];
  const maxCharsPerSample = samplePages.length > 1 ? 5500 : 12000;

  for (let i = 0; i < samplePages.length; i++) {
    const page = samplePages[i]!;
    const rawSnapshot = await loadPageSnapshot(page, runDir);
    const trimmed = rawSnapshot.trim().slice(0, maxCharsPerSample);
    if (trimmed) {
      if (samplePages.length > 1) {
        snapshotSnippets.push(`--- Sample ${i + 1} (${page.finalUrl || page.url}) ---\n${trimmed}`);
      } else {
        snapshotSnippets.push(trimmed);
      }
    }
  }

  const combinedSnapshot = snapshotSnippets.join("\n\n");

  const prompt = `
You are an expert software architect and product analyst. Analyze this web application screen ${group.isPatternGroup ? "(which represents a parameterized screen template group)" : ""}.

Target pattern/URL: ${group.pattern}
Screen sample titles: ${titles || "(none)"}
${headings ? `Key Headings:\n${headings}\n` : ""}

Below is the accessibility tree snapshot of the screen captured by agent-browser.
It shows the real UI elements (navigation, buttons, inputs, links, forms, tables, headings, and dialogs):

\`\`\`text
${combinedSnapshot || "(no snapshot available)"}
\`\`\`

Based on the agent-browser accessibility snapshot, return ONLY valid JSON matching this schema:
{
  "screenName": "Concise human-friendly name for this screen (e.g. 'Issue Details & Triage Viewer')",
  "screenType": "Categorical screen type, e.g. 'dashboard', 'detail-view', 'list-management', 'form', 'settings', 'auth', 'analytics'",
  "summary": "2-3 sentence functional summary of what this screen does based on its UI elements",
  "purpose": "Primary user/business purpose of this screen in the application",
  "keyWorkflows": ["Specific actions/workflows a user can perform on this screen derived from buttons and inputs"],
  "dataEntities": ["Business entities, data records, or domain objects displayed or managed here"],
  "uiComponents": ["Key UI sections, widgets, tables, feeds, or control panels visible in the snapshot"],
  "keywords": ["10-15 specific domain, technical, workflow, and search keywords for this screen"]
}
`;

  try {
    const response = await client.chat({
      model,
      messages: [
        { role: "user", content: prompt }
      ],
      format: "json",
      stream: false,
      options: {
        temperature: 0.2,
        num_ctx: 8192
      }
    });

    if (!response.message?.content) {
      throw new Error("Ollama returned an empty response.");
    }

    return parseScreenAnalysis(response.message.content, group);
  } catch (err) {
    console.warn(`  ⚠️ AI screen analysis fallback for ${group.pattern}: ${(err as Error).message}`);
    return createFallbackScreenAnalysis(group, titles);
  }
}


/**
 * Loads the raw agent-browser accessibility tree snapshot for a crawled page.
 * Prioritizes:
 * 1. In-memory page.snapshot
 * 2. .snapshot.txt file generated by agent-browser
 * 3. .json page data file (contains full snapshot)
 * 4. Fallback to page.text
 */
export async function loadPageSnapshot(page: CrawledPage, runDir?: string): Promise<string> {
  // 1. Direct in-memory snapshot if available
  if ((page as any).snapshot && typeof (page as any).snapshot === "string") {
    return (page as any).snapshot;
  }

  // 2. Read from snapshotFile (.snapshot.txt artifact)
  if (page.snapshotFile) {
    const candidatePaths = [
      page.snapshotFile,
      runDir ? path.join(runDir, page.snapshotFile) : null,
      runDir ? path.join(runDir, "pages", path.basename(page.snapshotFile)) : null
    ].filter((p): p is string => typeof p === "string" && fs.existsSync(p));

    if (candidatePaths.length > 0) {
      try {
        const content = await readFile(candidatePaths[0]!, "utf8");
        if (content.trim()) return content;
      } catch {
        // Continue to fallback
      }
    }
  }

  // 3. Read from dataFile (.json artifact containing captured snapshot)
  if (page.dataFile) {
    const candidatePaths = [
      page.dataFile,
      runDir ? path.join(runDir, page.dataFile) : null,
      runDir ? path.join(runDir, "pages", path.basename(page.dataFile)) : null
    ].filter((p): p is string => typeof p === "string" && fs.existsSync(p));

    if (candidatePaths.length > 0) {
      try {
        const raw = await readFile(candidatePaths[0]!, "utf8");
        const parsed = JSON.parse(raw);
        if (typeof parsed.snapshot === "string" && parsed.snapshot.trim()) {
          return parsed.snapshot;
        }
      } catch {
        // Continue to fallback
      }
    }
  }

  // 4. Fallback to page.text if no snapshot artifact is available
  return page.text || "";
}

function parseScreenAnalysis(
  content: string,
  group: ScreenGroup
): Omit<ScreenKnowledge, "screenId" | "pattern" | "isPatternGroup" | "sampleUrls"> {
  try {
    const cleaned = content.trim().replace(/^```(?:json)?\s*/i, "").replace(/\s*```$/, "");
    const parsed = JSON.parse(cleaned);

    return {
      screenName: typeof parsed.screenName === "string" ? parsed.screenName : deriveDefaultName(group),
      screenType: typeof parsed.screenType === "string" ? parsed.screenType : "page",
      summary: typeof parsed.summary === "string" ? parsed.summary : "Screen functionality summary unavailable.",
      purpose: typeof parsed.purpose === "string" ? parsed.purpose : "Application interface screen.",
      keyWorkflows: Array.isArray(parsed.keyWorkflows) ? parsed.keyWorkflows.map(String).slice(0, 10) : [],
      dataEntities: Array.isArray(parsed.dataEntities) ? parsed.dataEntities.map(String).slice(0, 10) : [],
      uiComponents: Array.isArray(parsed.uiComponents) ? parsed.uiComponents.map(String).slice(0, 10) : [],
      keywords: Array.isArray(parsed.keywords) ? parsed.keywords.map(String).slice(0, 20) : [],
      isFallback: false
    };
  } catch {
    return createFallbackScreenAnalysis(group, "");
  }
}

export function deriveDefaultName(group: ScreenGroup): string {
  try {
    const parsed = new URL(group.pattern);
    const lastSeg = parsed.pathname.split("/").filter(Boolean).pop() || "home";
    const clean = lastSeg.replace(/\{\{id\}\}/g, "").replace(/[-_]+/g, " ").trim();
    return clean ? `${clean.charAt(0).toUpperCase() + clean.slice(1)} Screen` : "Home Screen";
  } catch {
    return "Application Screen";
  }
}

/**
 * Loads previously saved screen knowledge from knowledge.json and screens/ directory
 * so that subsequent runs can reuse already-analyzed screens without re-invoking Ollama.
 */
export async function loadSavedScreenKnowledge(
  runDir: string
): Promise<Map<string, ScreenKnowledge>> {
  const map = new Map<string, ScreenKnowledge>();

  // 1. Read from knowledge.json if present
  const knowledgePath = path.join(runDir, "knowledge.json");
  if (fs.existsSync(knowledgePath)) {
    try {
      const data = await readJsonFile<CrawlKnowledgeResult>(knowledgePath);
      if (data && Array.isArray(data.screens)) {
        for (const scr of data.screens) {
          if (scr && scr.pattern && scr.screenName) {
            map.set(scr.pattern, scr);
          }
        }
      }
    } catch {
      // Continue to check individual screen files
    }
  }

  // 2. Read from screens/ directory if present (in case knowledge.json was partial)
  const screensDir = path.join(runDir, "screens");
  if (fs.existsSync(screensDir)) {
    try {
      const files = await fs.promises.readdir(screensDir);
      for (const file of files) {
        if (file.endsWith(".json")) {
          try {
            const raw = await readFile(path.join(screensDir, file), "utf8");
            const scr = JSON.parse(raw) as ScreenKnowledge;
            if (scr && scr.pattern && scr.screenName && !map.has(scr.pattern)) {
              map.set(scr.pattern, scr);
            }
          } catch {
            // Ignore malformed individual file
          }
        }
      }
    } catch {
      // Continue
    }
  }

  return map;
}

/**
 * Main function that consumes crawl output, analyzes screens with Ollama
 * using agent-browser accessibility tree snapshots, and produces structured knowledge.
 * Automatically persists each screen as it finishes and resumes existing screens on repeat runs.
 */
export async function generateCrawlKnowledge(
  options: GenerateKnowledgeOptions
): Promise<CrawlKnowledgeResult> {
  const { ollamaClient, ollamaModel } = getOllamaClient(options)

  let report = options.report;
  let runDir = options.runDir;

  if (!report) {
    let reportFile = options.reportPath;
    if (!reportFile && runDir) {
      reportFile = path.join(runDir, "report.json");
    }
    if (!reportFile) {
      throw new Error("Either report, reportPath, or runDir must be provided.");
    }
    report = await readJsonFile<CrawlReport>(reportFile);
    if (!runDir) {
      runDir = path.dirname(reportFile);
    }
  }

  // Load existing saved screen analyses to resume/reuse prior work
  const existingSaved = (runDir && !options.forceReanalyze)
    ? await loadSavedScreenKnowledge(runDir)
    : new Map<string, ScreenKnowledge>();

  if (existingSaved.size > 0) {
    console.log(`   📂 Found ${existingSaved.size} previously saved screen knowledge record(s) in ${runDir}`);
  }

  const groups = groupPagesForKnowledge(report.pages);
  const screens: ScreenKnowledge[] = [];
  const keywordFrequency = new Map<string, number>();

  let screenIndex = 0;
  for (const group of groups) {
    screenIndex += 1;
    const screenId = `screen-${String(screenIndex).padStart(3, "0")}`;
    const sampleUrls = group.pages.map((p) => p.finalUrl || p.url).slice(0, 5);

    let analysis: Omit<ScreenKnowledge, "screenId" | "pattern" | "isPatternGroup" | "sampleUrls">;

    const cached = existingSaved.get(group.pattern);
    // Reuse cached knowledge if it exists, is not a fallback error, and forceReanalyze is false
    if (cached && !cached.isFallback && !options.forceReanalyze) {
      console.log(`   ⏩ [${screenIndex}/${groups.length}] Reusing saved knowledge for ${group.pattern} (${cached.screenName})`);
      analysis = {
        screenName: cached.screenName,
        screenType: cached.screenType,
        summary: cached.summary,
        purpose: cached.purpose,
        keyWorkflows: cached.keyWorkflows ?? [],
        dataEntities: cached.dataEntities ?? [],
        uiComponents: cached.uiComponents ?? [],
        keywords: cached.keywords ?? [],
        isFallback: false
      };
    } else {
      console.log(`   🤖 [${screenIndex}/${groups.length}] Analyzing with Ollama: ${group.pattern}...`);
      analysis = await analyzeScreenWithOllama(ollamaClient, ollamaModel, group, runDir);
    }

    const screen: ScreenKnowledge = {
      screenId,
      pattern: group.pattern,
      isPatternGroup: group.isPatternGroup,
      sampleUrls,
      screenFile: runDir ? `screens/${screenId}.json` : undefined,
      ...analysis
    };

    screens.push(screen);

    for (const kw of screen.keywords) {
      const normalized = kw.trim().toLowerCase();
      if (normalized.length > 2) {
        keywordFrequency.set(normalized, (keywordFrequency.get(normalized) ?? 0) + 1);
      }
    }

    // Immediately persist incremental state after processing each screen
    if (runDir && fs.existsSync(runDir)) {
      const intermediateKeywords = Array.from(keywordFrequency.entries())
        .sort((a, b) => b[1] - a[1])
        .map(([kw]) => kw)
        .slice(0, 30);

      await persistScreenKnowledgeState(runDir, screen, {
        startUrl: report.startUrl,
        generatedAt: new Date().toISOString(),
        ollamaModel,
        totalScreens: screens.length,
        totalPatternGroups: screens.filter((s) => s.isPatternGroup).length,
        screens,
        globalKeywords: intermediateKeywords,
        siteSummary: `Knowledge synthesis of ${report.startUrl} (${screens.length} of ${groups.length} screens analyzed).`
      });
      console.log(`   ✓ Persisted ${screenId} (${screen.screenName})`);
    }
  }

  // Top global keywords sorted by frequency across screens
  const globalKeywords = Array.from(keywordFrequency.entries())
    .sort((a, b) => b[1] - a[1])
    .map(([kw]) => kw)
    .slice(0, 30);

  const totalPatternGroups = screens.filter((s) => s.isPatternGroup).length;
  const siteSummary = `Knowledge synthesis of ${report.startUrl} covering ${screens.length} distinct functional screens (${totalPatternGroups} dynamic pattern templates).`;

  const result: CrawlKnowledgeResult = {
    startUrl: report.startUrl,
    generatedAt: new Date().toISOString(),
    ollamaModel,
    totalScreens: screens.length,
    totalPatternGroups,
    screens,
    globalKeywords,
    siteSummary
  };

  // Final update of cumulative knowledge.json and knowledge.md
  if (runDir && fs.existsSync(runDir)) {
    await writeJson(path.join(runDir, "knowledge.json"), result);
    await writeFile(
      path.join(runDir, "knowledge.md"),
      buildKnowledgeMarkdown(result, runDir),
      "utf8"
    );
  }

  return result;
}
