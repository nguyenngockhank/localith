import type { CrawlReport } from "../types.js";
import { escapeCell } from "./crawl/crawler.js";

export function buildMarkdownReport(report: CrawlReport, runDir: string): string {
    const lines: string[] = [
        "# Website Scan Report",
        "",
        `- **Start URL:** ${report.startUrl}`,
        `- **Started:** ${report.startedAt}`,
        `- **Finished:** ${report.finishedAt}`,
        `- **Depth limit:** ${report.settings.maxDepth}`,
        `- **Page cap:** ${report.settings.maxPages}`,
        `- **Pattern cap:** ${report.settings.maxPagesPerPattern ?? 3} samples per dynamic pattern at depth > 1`,
        `- **AI model:** ${report.settings.useAi ? report.settings.ollamaModel : "disabled"}`,
        `- **robots.txt:** ${report.settings.respectRobots ? "respected" : "ignored"}`,
        `- **Auth wall handling:** ${report.settings.auth.enabled ? "enabled" : "disabled"}`,
        "",
        "## Summary",
        "",
        `- Discovered URLs: ${report.totals.discovered}`,
        `- Visited URLs: ${report.totals.visited}`,
        `- Successful pages: ${report.totals.succeeded}`,
        `- Failed pages: ${report.totals.failed}`,
        `- Skipped by robots.txt: ${report.totals.skippedByRobots}`,
        `- Skipped by auth wall: ${report.totals.skippedByAuth}`,
        `- Skipped by pattern limit: ${report.totals.skippedByPattern ?? 0}`,
        "",
        "## Pages",
        "",
        "| # | Depth | Status | Title / Detail | URL |",
        "|---:|---:|---|---|---|"
    ];

    report.pages.forEach((page, index) => {
        const detail = page.title || (page.pattern && page.status === "skipped" ? `[pattern group] ${page.pattern}` : page.error) || "";
        lines.push(
            `| ${index + 1} | ${page.depth} | ${page.status} | ${escapeCell(detail)} | ${escapeCell(page.finalUrl)} |`
        );
    });

    const patternEntries = Object.entries(report.patternGroups ?? {});
    if (patternEntries.length > 0) {
        lines.push("", "## Pattern Groups", "");
        lines.push("| Pattern | Crawled Samples | Skipped URLs |", "|---|---:|---:|");
        for (const [pattern, counts] of patternEntries) {
            lines.push(
                `| \`${escapeCell(pattern)}\` | ${counts.crawled} | ${counts.skipped} |`
            );
        }
    }

    lines.push("", "## AI Analysis", "");
    for (const page of report.pages.filter((item) => item.analysis)) {
        const analysis = page.analysis!;
        lines.push(
            `### ${page.title || page.finalUrl}`,
            "",
            `- **URL:** ${page.finalUrl}`,
            `- **Type:** ${analysis.page_type}`,
            `- **Summary:** ${analysis.summary}`,
            `- **Topics:** ${analysis.key_topics.join(", ") || "—"}`,
            `- **Entities:** ${analysis.important_entities.join(", ") || "—"}`,
            "- **Recommendations:**",
            ...(analysis.recommendations.length
                ? analysis.recommendations.map((item) => `  - ${item}`)
                : ["  - —"]),
            ""
        );
    }

    const authWalls = report.pages.filter((page) => page.authWall);
    if (authWalls.length > 0) {
        lines.push("## Auth walls", "");
        lines.push("| URL | Status | Sign-in attempted |", "|---|---|---|");
        for (const page of authWalls) {
            lines.push(
                `| ${escapeCell(page.finalUrl)} | ${page.status} | ${page.authHandled ? "yes" : "no"} |`
            );
        }
        lines.push("");
    }

    lines.push(
        "## Files",
        "",
        "- `report.json`: machine-readable crawl report",
        "- `queue.json`: pending queue of uncrawled URLs for resuming scans",
        "- `auth-state.json`: saved browser cookies and session state (when authenticated)",
        "- `pages/*.json`: page data and full accessibility snapshot",
        "- `pages/*.snapshot.txt`: raw accessibility snapshots",
        "",
        "_Generated by Local Website Scanner._",
        ""
    );

    return lines.join("\n");
}
